const embedSource=read('base44/shared/campaignEmbeds.ts');
const emitted=ts.transpileModule(embedSource,{compilerOptions:{
 module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022,
}}).outputText;
const embed=await import('data:text/javascript;base64,'+Buffer.from(emitted).toString('base64'));
const id='6ac9ff112233445566aabbcc';
const iframe='<iframe src="https://interplanetaryfund.com/embed/campaign/'+id+'" title="Donate"></iframe>';
const converted=embed.normalizeCampaignEmbeds('Hello\n'+iframe+'\nThanks!');
assert.match(converted,new RegExp('\\[campaign:'+id+'\\]'));
assert.deepEqual(embed.campaignIdsFromText(converted),[id]);
assert.equal(embed.campaignIdsFromText('https://evil.example/campaign/'+id).length,0);
assert.doesNotMatch(embed.normalizeCampaignEmbeds('<script>alert(1)</script>'),/<script/);
const {splitCampaignContent,embedSnippet,extractCampaignIds}=await import('../src/lib/campaignEmbed.js');
const plain=splitCampaignContent('My cause https://interplanetaryfund.com/campaign/'+id+' thanks');
assert.ok(plain.some(x=>x.type==='campaign'&&x.id===id));
assert.ok(splitCampaignContent(embedSnippet(id)).some(x=>x.type==='campaign'&&x.id===id));
assert.deepEqual(extractCampaignIds('https://interplanetaryfund.com/campaign/'+id),[id]);
