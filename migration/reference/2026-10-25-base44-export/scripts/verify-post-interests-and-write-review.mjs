import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const schema=JSON.parse(read('base44/entities/PostInterest.jsonc'));
assert.equal(schema.name,'PostInterest');
for(const op of ['create','read','update','delete'])assert.equal(schema.rls[op]['data.user_id'],'{{user.id}}');
const backend=read('base44/functions/managePostInterest/entry.ts');
assert.match(backend,/assertActiveAccount\(base44\)/);
assert.match(backend,/filter\(\{user_id:user.id,post_id:postId\}/);
assert.match(backend,/entities\.SocialPost\.updateMany/);
assert.match(backend,/\$inc:\{likes_count:delta\}/);
assert.ok(!backend.includes('base44.entities.SocialPost.update(postId'),'No client-like post edit');
const social=read('src/components/social/SocialFeed.jsx');
assert.match(social,/managePostInterest/);
assert.ok(!social.includes('base44.entities.SocialPost.update(post.id, { likes_count:'));
assert.match(social,/onSave=\{\(\)=>handleInterest\(p,"saved"\)\}/);
const card=read('src/components/social/PostCard.jsx');
assert.match(card,/aria-pressed=\{liked\}/);
assert.match(card,/aria-pressed=\{saved\}/);
const ctx=read('base44/functions/getAgentAccountContext/entry.ts');
assert.match(ctx,/liked_and_saved_posts:/);
assert.match(ctx,/DistributedPost\.filter\(\{ created_by_id: user.id \}/);
const editor=read('src/components/agents/AgentContentReview.jsx');
assert.match(editor,/Edit draft/);
assert.match(editor,/mode:action/);
const draft=read('base44/functions/manageAgentContentDraft/entry.ts');
assert.match(draft,/Destination fields cannot change during a draft edit/);
console.log('PASS: per-user like/save access, account-interest visibility, draft editing and destination locks');
