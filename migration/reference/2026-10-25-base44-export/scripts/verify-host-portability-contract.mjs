import assert from "node:assert/strict";
import fs from "node:fs";

const read = p => fs.readFileSync(new URL("../" + p, import.meta.url), "utf8");
const runtime = read("src/lib/runtimeContract.js");
const gateway = read("src/lib/adminAgentGateway.js");
const docs = read("docs/HOST_PORTABILITY_AND_ADMIN_AGENT_CONTRACT.md");
const client = read("src/api/base44Client.js");
const panel = read("src/components/agents/AdminDevelopmentChat.jsx");
const authContext = read("src/lib/AuthContext.jsx");
const worker = read("host/gateway/worker.js");
const verifyAdmin = read("base44/functions/verifyAdminGateway/entry.ts");
const executeAdmin = read("base44/functions/executeAdminAgentRequest/entry.ts");
const auditAdmin = read("base44/functions/auditAdminAgentGateway/entry.ts");
const envExample = read(".env.example");

assert.match(runtime, /VITE_BASE44_APP_ID/);
assert.match(runtime, /VITE_BASE44_APP_BASE_URL/);
assert.match(runtime, /VITE_ADMIN_AGENT_API_URL/);
assert.match(gateway, /\/v1\/admin\/agents\/session/);
assert.match(gateway, /\/v1\/admin\/agents\/message/);
assert.match(gateway, /\/v1\/admin\/agents\/status/);
assert.match(gateway, /verifyAdminGateway/, "When there is no separately configured gateway, native Base44 must verify the canonical super-admin role");
assert.match(gateway, /executeAdminAgentRequest/, "A verified Base44 super-admin must be able to execute and poll the existing backend directly");
assert.match(gateway, /adminGatewayMode/, "The separate admin gateway must be optional for Base44-hosted functionality");
assert.match(gateway, /authorization.*Bearer/s, "Admin gateway client must forward the authenticated Base44 bearer token");
assert.match(docs, /IFUND_ADMIN_AGENT_KEY/);
assert.match(docs, /split-brain/i);
assert.match(docs, /same authoritative Base44 application\/data plane/i);
assert.match(docs, /MUST NOT fail solely because a paid provider capability is unavailable/i);
assert.match(docs, /Base44 two-way GitHub sync/i);
assert.match(docs, /manual-sync-required/i);
assert.match(client, /runtimeContract\.appId/);
assert.match(client, /runtimeContract\.appBaseUrl/);
assert.match(client, /isNativeBase44Host/, "Client must distinguish native Base44 hosting from alternate hosts");
assert.match(client, /base44\\\.app/, "Native Base44 host detection must target base44.app");
assert.match(client, /if\s*\(!isNativeBase44Host\s*&&\s*appBaseUrl\)/, "Alternate hosts must explicitly route Base44 auth/API traffic to the canonical backend");
assert.match(client, /clientConfig\.serverUrl\s*=\s*appBaseUrl/, "Alternate hosts must set the canonical Base44 server URL");
assert.doesNotMatch(client, /serverUrl:\\s*appBaseUrl[,:]/, "Native Base44 must not be forced through the alternate-host server override");
assert.doesNotMatch(client, /serverUrl:\s*['\"]{2}/, "Hosted frontends must not use an empty same-origin Base44 server URL");
assert.match(panel, /createAdminAgentSession/);
assert.match(panel, /Verify admin access/, "The native admin option must be visible without requesting a meaningless key");
for (const agent of ["chief_of_staff", "connection_discovery_agent", "managed_connection_agent", "outreach_agent"]) {
  assert.ok(fs.existsSync(new URL(`../base44/agents/${agent}.jsonc`, import.meta.url)), `Admin chooser must only offer a defined ${agent}`);
}
assert.match(worker, /IFUND_AGENT_EXECUTE_URL/);
const agentRuntime = worker.split("async function callAgentRuntime(")[1]?.split("// Preview-only independent identity verification")[0] || "";
assert.match(agentRuntime, /endpoint\.protocol!=="https:"/, "Admin credentials must only be forwarded to HTTPS agent runtimes");
assert.match(agentRuntime, /redirect:"manual"/, "Admin credentials must never follow agent-runtime redirects");
assert.match(agentRuntime, /r\.status>=300 && r\.status<400/, "Agent-runtime redirects must fail closed");
assert.match(worker, /degraded.*true/);
assert.match(worker, /IFUND_SESSION_SECRET/);
assert.match(worker, /!env\.IFUND_ADMIN_AGENT_KEY\s*\|\|\s*!env\.IFUND_SESSION_SECRET/, "Missing gateway secrets must fail closed");
assert.match(worker, /sessionSignature/);
assert.match(worker, /access-control-allow-headers.*authorization/s, "Gateway CORS must allow the Base44 authorization header");
assert.match(worker, /\/v1\/admin\/agents\/status/);
assert.match(worker, /forwardedAdminAuth/);
assert.doesNotMatch(worker, /sessions=new Map/);
assert.match(verifyAdmin, /isSuperAdminOwner\(user\)/);
assert.match(executeAdmin, /AgentActivity\.create/);
assert.match(executeAdmin, /agents\.createConversation/);
assert.match(executeAdmin, /agents\.addMessage/);
assert.match(executeAdmin, /agents\.getConversation/);
assert.match(executeAdmin, /execution_status:\s*'processing'/);
assert.doesNotMatch(executeAdmin, /recorded_pending_runtime/, "Admin agent execution must not regress to the queue-only placeholder");
assert.match(auditAdmin, /logAudit/);
assert.match(envExample, /VITE_ADMIN_AGENT_API_URL/);
assert.doesNotMatch(envExample, /IFUND_ADMIN_AGENT_KEY=/);
console.log("Host portability and admin-agent contract passed");
