import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const source = readFileSync(
  new URL("../src/pages/CreateCampaign.jsx", import.meta.url),
  "utf8",
);

test("campaign creator distinguishes a basic outline from AI-assisted writing", () => {
  assert.match(source, /suggestions\.assistance === "outline"/);
  assert.match(source, /A basic outline is ready/);
  assert.match(source, /It was not generated by AI/);

  assert.match(source, /AI-assisted writing suggestions are ready/);
  assert.match(source, /Suggested illustration concept \(no image generated\)/);
  assert.doesNotMatch(source, /Suggestions are ready\. Choose which ideas to apply/);
});
