import { useEffect, useRef, useState } from "react";
import { Link, useNavigate } from "react-router-dom";
import { authClient } from "@/api/auth";
import { uploadCampaignCover } from "@/api/campaignCovers";
import PremiumOpportunity from "@/components/subscriptions/PremiumOpportunity";
import PublishingWorkflowNav from "@/components/communications/PublishingWorkflowNav";
import TrialCreationBalance from "@/components/subscriptions/TrialCreationBalance";
import { prepareReferenceJpeg, decodeGeneratedArtwork } from "@/lib/imageArtwork.mjs";
import { overlayExactArtworkCaption, validateArtworkCaption } from "@/lib/exactArtworkCaption.mjs";
import { stageMediaForOptimization } from "@/lib/mediaDraftHandoff.mjs";

const STYLES = [
  ["interstellar", "Interstellar"],
  ["futuristic", "Futuristic"],
  ["cyberpunk", "Cyberpunk"],
  ["comic", "Comic illustration"],
  ["hyper-realistic-simulated-event", "Hyper-realistic simulated event"],
];
const field = "mt-2 w-full min-h-11 rounded-xl border border-input bg-background px-4 py-2";
const button = "ifund-interactive min-h-11 rounded-xl border border-border px-4 py-2 font-semibold disabled:opacity-60";

/**
 * AI artwork must be generated by the provider-backed, quota-limited Worker.
 * Preview and upload are two separately verified actions. No image is attached
 * to a campaign merely because it was generated or saved in object storage.
 */
export default function AIImageStudio({ embedded = false }) {
  const navigate = useNavigate();
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [style, setStyle] = useState("ifund");
  const [exactCaption,setExactCaption] = useState("");
  const [access,setAccess] = useState(null);
  const [referenceFile, setReferenceFile] = useState(null);
  const [confirmedRights, setConfirmedRights] = useState(false);
  const [artworkKind, setArtworkKind] = useState("generated");
  const operationLock = useRef(false);
  const [busy, setBusy] = useState("");
  const [imageUrl, setImageUrl] = useState("");
  const [file, setFile] = useState(null);
  const [savedUrl, setSavedUrl] = useState("");
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");
  const objectUrl = useRef("");
  const mounted = useRef(true);
  useEffect(() => {
    authClient().rpc("ifund_ai_image_access_status").then(({data,error})=>{if(mounted.current&&!error)setAccess(data);}).catch(()=>{});
  },[]);
  useEffect(() => {
    mounted.current = true;
    return () => {
      mounted.current = false;
      if (objectUrl.current) URL.revokeObjectURL(objectUrl.current);
    };
  }, []);

  function clearArtwork() {
    if (objectUrl.current) URL.revokeObjectURL(objectUrl.current);
    objectUrl.current = "";
    setImageUrl("");
    setFile(null);
    setSavedUrl("");
  }
  function invalidateArtwork() {
    clearArtwork();
    setMessage("");
    setError("");
  }
  async function generate(event, improve = false) {
    event?.preventDefault();
    if (operationLock.current || busy) return;
    try { validateArtworkCaption(exactCaption); } catch (cause) { setError(cause.message); return; }
    if (title.trim().length < 4 || title.trim().length > 150 ||
        description.trim().length < 20 || description.trim().length > 900) {
      setError("Enter a valid campaign title and description before continuing.");
      return;
    }
    if (improve && (!referenceFile || !confirmedRights)) {
      setError("Choose a photo you may edit and confirm your permission before improving it.");
      return;
    }
    operationLock.current = true;
    setBusy(improve ? "improve" : "generate"); setError(""); setMessage("");
    clearArtwork();
    try {
      const reference = improve ? await prepareReferenceJpeg(referenceFile) : null;
      const client = authClient();
      const before = await client.auth.getUser();
      const { data: session, error: sessionError } = await client.auth.getSession();
      if (before.error || sessionError || !before.data?.user?.id ||
          before.data.user.id !== session?.session?.user?.id ||
          !session.session.access_token)
        throw new Error("Sign in to a verified account before generating artwork.");
      const response = await fetch(improve ? "/api/ai/images/improve" : "/api/ai/images/generate", {
        method: "POST",
        headers: {
          Authorization: "Bearer " + session.session.access_token,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          title: title.trim(), description: description.trim(), style,
          ...(!improve ? { purpose: "media" } : {}),
          ...(improve ? { reference_jpeg: reference.reference_jpeg, confirmed_rights: true } : {}),
        }),
      });
      const result = await response.json().catch(() => null);
      if (!response.ok)
        throw new Error(result?.error || "Image generation is currently unavailable.");
      if (improve && result?.improved !== true)
        throw new Error("The image improvement response could not be verified.");
      const bytes = decodeGeneratedArtwork(result);
      const raw = new File([bytes], improve ? "ifund-improved-cover.jpg" : "ifund-generated-cover.jpg", {
        type: "image/jpeg",
      });
      const jpeg = await overlayExactArtworkCaption(raw,exactCaption);
      const after = await client.auth.getUser();
      if (after.error || after.data?.user?.id !== before.data.user.id)
        throw new Error("Your account changed before the image could be shown.");
      if (!mounted.current) return;
      const url = URL.createObjectURL(jpeg);
      objectUrl.current = url;
      setFile(jpeg);
      setImageUrl(url);
      window.dispatchEvent(new Event("ifund-ai-creation-completed"));
      setArtworkKind(improve ? "improved" : "generated");
      setMessage(style === "hyper-realistic-simulated-event"
        ? "AI-simulated event illustration, not documentary evidence. Review it and keep this label visible wherever it is published."
        : improve
          ? "The selected image was improved with AI. Review it before saving; the original file was not stored by this action."
          : "Artwork generated. Review it before saving or using it in a campaign.");
    } catch (cause) {
      setError(cause?.message || "Artwork generation failed.");
    } finally {
      operationLock.current = false;
      setBusy("");
    }
  }

  async function openPlatformOptimizer() {
    if (!file || busy) return;
    try {
      const { data, error } = await authClient().auth.getUser();
      if (error || !data?.user?.id) throw new Error("Sign in to optimize this illustration.");
      stageMediaForOptimization(file, data.user.id);
      navigate("/communications?tab=media&tool=optimization");
    } catch (cause) { setError(cause.message || "Unable to prepare image optimization."); }
  }
  async function save() {
    if (operationLock.current || busy || !file) return;
    operationLock.current = true;
    setBusy("upload"); setError(""); setMessage("");
    try {
      const url = await uploadCampaignCover(authClient(), file);
      if (!mounted.current) return;
      setSavedUrl(url);
      setMessage("The image was saved to your IFund public cover storage. It is not attached to a campaign until you choose it in the campaign editor and save.");
    } catch (cause) { setError(cause?.message || "Artwork could not be saved."); }
    finally { operationLock.current = false; setBusy(""); }
  }
  async function copy() {
    if (!savedUrl) return;
    try {
      await navigator.clipboard.writeText(savedUrl);
      setMessage("Cover link copied. Paste it into the campaign cover field and save your campaign draft.");
    } catch { setError("Copy is unavailable. Select and copy the saved cover link below."); }
  }

  return <main className="mx-auto max-w-5xl space-y-6 px-4 py-8 sm:px-8">
    {!embedded && <PublishingWorkflowNav current="creative"/>}
    <header className="space-y-2">
      <p className="text-xs font-semibold uppercase tracking-widest text-cyan-600">IFund Campaign Studio</p>
      <h1 className="text-3xl font-bold">AI Image Studio</h1>
      <p className="text-sm text-muted-foreground">
        Create original illustrated campaign artwork or improve your own image with Cloudflare Workers AI.
        Eligible verified members can generate artwork during a 24-hour signup trial and earned 24-hour referral extensions. Paid subscribers get up to 50 image-generation or improvement attempts per rolling seven days. All requests remain subject to the shared provider budget, 10-second pacing, and service availability. Nothing is purchased or published automatically.
      </p>
      {access&&<p role="status" className="text-sm text-muted-foreground">Membership: {access.entitled?"Eligible":"Not currently eligible"}{access.trial_enabled&&access.trial_expires_at?" · Trial through "+new Date(access.trial_expires_at).toLocaleString():""}{access.paid_weekly_limit===50?" · Paid artwork: "+access.paid_weekly_remaining+" of 50 attempts available this rolling week":""}{!access.trial_enabled?" · Signup trial not activated on this deployment":""}. Referral hours remain available only when verified and activated.</p>}
    </header>
    <TrialCreationBalance />
    <PremiumOpportunity context="artwork" />
    <form onSubmit={generate} className="space-y-5 rounded-2xl border border-border bg-card p-5 sm:p-7">
      <h2 className="text-xl font-semibold">Illustrate your cause</h2>
      <label className="block text-sm font-medium">Campaign title
        <input className={field} value={title} onChange={e => { setTitle(e.target.value); invalidateArtwork(); }}
          required minLength={4} maxLength={150} disabled={Boolean(busy)} />
      </label>
      <label className="block text-sm font-medium">What does the fundraiser support?
        <textarea className={field} rows={4} minLength={20} maxLength={900}
          value={description} onChange={e => { setDescription(e.target.value); invalidateArtwork(); }}
          required disabled={Boolean(busy)} />
      </label>
      <label className="block text-sm font-medium">Artwork style
        <select className={field} value={style} onChange={e => { setStyle(e.target.value); invalidateArtwork(); }} disabled={Boolean(busy)}>
          {STYLES.map(([value,label]) => <option key={value} value={value}>{label}</option>)}
        </select>
      </label>
      <section className="space-y-3 rounded-xl border border-border p-4" aria-label="Exact caption text">
        <h3 className="font-semibold">Words on the illustration (optional)</h3>
        <p className="text-sm text-muted-foreground">Images are generated without text. iFund adds your exact approved words afterward so the model cannot misspell them. Copy your title exactly, or enter a corrected phrase yourself. Check the final preview before saving.</p>
        <div className="flex flex-wrap gap-2"><button type="button" className={button} disabled={Boolean(busy)} onClick={()=>{setExactCaption(title.slice(0,100));invalidateArtwork();}}>Use title exactly</button>
          <button type="button" className={button} disabled={Boolean(busy)} onClick={()=>{setExactCaption("");invalidateArtwork();}}>No words</button></div>
        <label className="block text-sm font-medium">Exact caption to print
          <input className={field} maxLength={100} spellCheck={true} value={exactCaption} disabled={Boolean(busy)}
            onChange={e=>{setExactCaption(e.target.value);invalidateArtwork();}} placeholder="Your wording, spelled exactly as approved" />
        </label>
        <p className="text-xs text-muted-foreground">The text is rendered locally using a regular font; spelling is not generated by AI. Any unexpected letters in the background artwork must be reviewed before use.</p>
      </section>
      <section className="space-y-3 rounded-xl border border-border p-4" aria-label="Optional image improvement">
        <h3 className="font-semibold">Improve an image you already have (optional)</h3>
        <p className="text-xs text-muted-foreground">Choose a JPG, PNG, WebP or AVIF image up to 5 MB. The file is resized locally to a 480-pixel maximum and stripped of image metadata before submission to Cloudflare's image model. Do not submit confidential documents or images without permission.</p>
        <label className="block text-sm font-medium">Choose reference image
          <input className="mt-2 w-full rounded-xl border border-input bg-background p-3 text-sm"
            type="file" accept="image/jpeg,image/png,image/webp,image/avif" disabled={Boolean(busy)}
            onChange={e => {
              const next = e.currentTarget.files?.[0] || null;
              e.currentTarget.value = "";
              setReferenceFile(next);
              setConfirmedRights(false);
              invalidateArtwork();
            }} />
        </label>
        {referenceFile && <p className="break-all text-xs text-muted-foreground">Selected: {referenceFile.name}</p>}
        <label className="flex min-h-11 items-center gap-3 text-sm">
          <input type="checkbox" checked={confirmedRights} disabled={Boolean(busy) || !referenceFile}
            onChange={e => {
              setConfirmedRights(e.target.checked);
              if (!e.target.checked) invalidateArtwork();
            }} />
          I have permission to edit this image and agree to send its resized contents to Cloudflare Workers AI.
        </label>
        <button type="button" className={button}
          disabled={Boolean(busy) || !referenceFile || !confirmedRights}
          onClick={() => generate(null, true)}>
          {busy === "improve" ? "Improving illustration…" : "Improve selected image with AI"}
        </button>
      </section>
      <p className="text-xs text-muted-foreground">Use illustrative imagery only; do not imply that an AI-created person or scene is a real beneficiary, donor or event.</p>
      <button type="submit" className="ifund-interactive min-h-11 rounded-xl bg-primary px-5 font-semibold text-primary-foreground disabled:opacity-60" disabled={Boolean(busy)}>
        {busy === "generate" ? "Generating artwork…" : "Generate original artwork"}
      </button>
    </form>
    {error && <p role="alert" className="ifund-feedback-error">{error}</p>}
    {message && <p role="status" className="ifund-feedback-success">{message}</p>}
    {imageUrl && <section className="space-y-4 rounded-2xl border border-border bg-card p-5">
      <h2 className="text-xl font-semibold">Review {artworkKind === "improved" ? "improved" : "generated"} illustration</h2>
      <img src={imageUrl} alt={"AI illustration for " + title} className="max-h-[550px] w-full rounded-xl object-contain" />
      <div className="flex flex-wrap gap-3">
        <button type="button" onClick={save} className={button} disabled={Boolean(busy) || Boolean(savedUrl)}>
          {busy === "upload" ? "Saving image…" : savedUrl ? "Image saved" : "Save to IFund cover storage"}
        </button>
        <a href={imageUrl} download={artworkKind === "improved" ? "ifund-improved-cover.jpg" : "ifund-generated-cover.jpg"} className={button}>Download JPEG</a>
        <button type="button" className={button} disabled={Boolean(busy)} onClick={openPlatformOptimizer}>Make platform versions</button>
      </div>
      {savedUrl && <div className="space-y-3">
        <label className="block text-sm font-medium">Saved public cover link
          <input type="text" readOnly value={savedUrl} className={field} onFocus={e=>e.target.select()}/>
        </label>
        <div className="flex flex-wrap gap-3">
          <button type="button" className={button} onClick={copy}>Copy cover link</button>
          <Link to="/create" className={button}>Open campaign editor</Link>
        </div>
        <p className="text-xs text-muted-foreground">In the campaign editor, paste this link into the cover URL field and save or publish your campaign to attach it.</p>
      </div>}
    </section>}
  </main>;
}
