import { useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { Bot, Sparkles, Send, ShieldCheck, ArrowUpRight } from "lucide-react";
import { SHOWCASE_CAMPAIGNS } from "@/lib/unifiedDemoJourney.mjs";

// Interactive *illustration* of a future agent conversation, not a model call.
// Real AI creation happens in the linked signed-in Cloudflare Workers AI Studio.
const AGENTS = [
  { id:"coach",name:"Campaign Coach",role:"Review needs, budget, and success measures" },
  { id:"story",name:"Story Agent",role:"Strengthen the campaign story and calls to action" },
  { id:"outreach",name:"Outreach Agent",role:"Plan consent-aware supporter communications" },
];

function response(agent, campaign, query) {
  const text=String(query||"").toLowerCase();
  const focus = text.includes("budget") || text.includes("cost")
    ? "budget"
    : text.includes("share") || text.includes("social") || text.includes("outreach")
      ? "outreach"
      : text.includes("story") || text.includes("title")
        ? "story"
        : agent === "outreach" ? "outreach" : agent === "story" ? "story" : "analysis";
  const opening = `This is an illustrative response for the fictional campaign “${campaign.title}”. It is not generated by a model.`;
  if (focus === "budget") return opening + " Before publishing, document actual vendor costs, quantities, and a contingency. Keep planned amounts separate from verified donations and never promise spending without evidence.";
  if (focus === "outreach") return opening + ` Lead with a transparent explanation of the need: ${campaign.need}. Draft one accessible, non-coercive supporter update. Only post to networks the organizer connected and authorized.`;
  if (focus === "story") return opening + ` A draft headline to review is: “${campaign.titles[0]}”. Explain the need, show a measurable plan, and invite voluntary support without fictionalizing real beneficiaries.`;
  return opening + ` First verify the need: ${campaign.need}. Next, check the spending plan, organizer permission, evidence, measurable milestones and public updates before recommending publication.`;
}

export default function AgentPreviewLab() {
  const [campaignId,setCampaignId] = useState(SHOWCASE_CAMPAIGNS[0].id);
  const [agent,setAgent] = useState("coach");
  const [prompt,setPrompt] = useState("");
  const [history,setHistory] = useState([]);
  const campaign=useMemo(()=>SHOWCASE_CAMPAIGNS.find(c=>c.id===campaignId)||SHOWCASE_CAMPAIGNS[0],[campaignId]);
  const selected=AGENTS.find(x=>x.id===agent)||AGENTS[0];
  function send(question) {
    const message=String(question||"").trim();
    if (!message || message.length>400) return;
    setHistory(items=>[...items.slice(-3),{question:message,reply:response(agent,campaign,message),agent:selected.name}]);
    setPrompt("");
  }
  return <section id="agent-preview" className="space-y-5 rounded-2xl border-2 border-violet-400/50 bg-[#091126] p-5 text-slate-100 sm:p-7" aria-label="Interactive example of iFund AI agent conversations">
    <header className="flex flex-wrap items-start gap-4">
      <div className="rounded-xl bg-violet-400/15 p-3"><Bot className="h-7 w-7 text-violet-200" aria-hidden="true"/></div>
      <div className="min-w-0 flex-1">
        <p className="text-xs font-bold uppercase tracking-[.2em] text-violet-300">AI Agent Mission Control · Interactive preview</p>
        <h2 className="mt-2 text-2xl font-semibold">Talk to the IFund agent team</h2>
        <p className="mt-2 text-sm text-slate-300">Choose a specialist and ask about a fictional campaign. This preview shows conversation design and example guidance; responses here are rules-based, <strong>not live AI inference</strong>.</p>
      </div>
    </header>
    <div className="grid gap-3 sm:grid-cols-3">
      {AGENTS.map(item=><button key={item.id} type="button" aria-pressed={agent===item.id}
        onClick={()=>setAgent(item.id)} className={"min-h-28 rounded-xl border p-3 text-left transition "+(agent===item.id?"border-violet-300 bg-violet-500/20":"border-slate-600 bg-slate-950/40 hover:border-violet-400/60")}>
        <strong className="block">{item.name}</strong><span className="mt-2 block text-xs text-slate-300">{item.role}</span>
      </button>)}
    </div>
    <label className="block text-sm font-semibold" htmlFor="agent-preview-campaign">Example campaign to analyze</label>
    <select id="agent-preview-campaign" value={campaignId} onChange={event=>{setCampaignId(event.target.value);setHistory([])}}
      className="min-h-11 w-full rounded-xl border border-slate-600 bg-slate-950 px-3 text-slate-100">
      {SHOWCASE_CAMPAIGNS.map(c=><option key={c.id} value={c.id}>{c.title}</option>)}
    </select>
    <div role="log" aria-live="polite" className="max-h-80 space-y-3 overflow-y-auto rounded-xl border border-slate-700 bg-slate-950/60 p-4">
      <p className="text-sm text-violet-200"><strong>{selected.name}:</strong> For this fictional example, I can show how an agent might review the campaign, improve its story or plan outreach. What would you like to explore?</p>
      {history.map((entry,i)=><div className="space-y-2 border-t border-slate-700 pt-3" key={i}>
        <p className="text-sm"><strong>You:</strong> {entry.question}</p>
        <p className="text-sm leading-6 text-slate-300"><strong className="text-violet-200">{entry.agent} (example):</strong> {entry.reply}</p>
      </div>)}
    </div>
    <div className="flex flex-wrap gap-2">
      {["Analyze this campaign","Improve the story","Review the budget","Suggest an outreach plan"].map(q=><button type="button" key={q} onClick={()=>send(q)}
        className="min-h-10 rounded-xl border border-violet-400/40 px-3 py-2 text-xs font-semibold hover:bg-violet-500/15">{q}</button>)}
    </div>
    <form className="flex flex-col gap-2 sm:flex-row" onSubmit={e=>{e.preventDefault();send(prompt)}}>
      <label className="sr-only" htmlFor="agent-preview-question">Ask the agent an example question</label>
      <input id="agent-preview-question" maxLength={400} value={prompt} onChange={e=>setPrompt(e.target.value)}
        placeholder="Ask about campaign story, goals or outreach…" className="min-h-11 min-w-0 flex-1 rounded-xl border border-slate-600 bg-slate-950 px-3 text-sm" />
      <button type="submit" disabled={!prompt.trim()} className="inline-flex min-h-11 items-center justify-center gap-2 rounded-xl bg-violet-500 px-5 font-bold text-white disabled:opacity-40"><Send size={16}/> Send preview</button>
    </form>
    <div className="rounded-xl border border-cyan-400/40 bg-cyan-400/10 p-4">
      <div className="flex items-center gap-2 text-cyan-100"><Sparkles size={20}/><strong>Try the functioning AI Campaign Studio</strong></div>
      <p className="mt-2 text-sm text-slate-200">The standalone sandbox uses Cloudflare Workers AI for actual five-title generation, two description options, full stories and section regeneration. Sign in to a demo account to make a real model request. The conversation preview above is illustrative only.</p>
      <a href="https://ifund-hackathon-demo.interplanetary-fund.workers.dev/create" target="_blank" rel="noopener noreferrer"
        className="mt-3 inline-flex min-h-11 items-center gap-2 rounded-xl bg-cyan-400 px-4 font-bold text-slate-950">Launch real AI campaign creation <ArrowUpRight size={17}/></a>
    </div>
    <p className="flex items-start gap-2 text-xs text-slate-300"><ShieldCheck size={16} className="shrink-0"/> No message is sent to a model or external platform from this preview, and no example feedback is recorded as real campaign analytics. Actual model generation is in the linked sandbox studio.</p>
    <Link to="/agents" className="inline-flex min-h-11 items-center underline text-sm text-cyan-200">Explore the live IFund agent workspaces</Link>
  </section>;
}
