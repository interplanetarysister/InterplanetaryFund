// ONE-TIME MIGRATION — Fix all existing campaign data (BOTH tables)
// =====================================================

export const migrateAllCampaigns = mutation({
  args: { sessionToken: v.string() },
  handler: async (ctx, { sessionToken }) => {
    await requireAdminSession(ctx, sessionToken, "campaigns");
    // Fix monitored campaigns
    const monitoredCampaigns = await ctx.db.query("monitoredCampaigns").collect();
    let fixed = 0;

    for (const campaign of monitoredCampaigns) {
      if (campaign.frozen) continue;
      const updates: any = {};
      if (!campaign.outreachEnabled && campaign.status === "active") updates.outreachEnabled = true;
      if (!campaign.aiTone) updates.aiTone = "Compassionate and empowering — warm but not saccharine, urgent but not desperate";
      if (!campaign.aiIdealDonors) updates.aiIdealDonors = "Socially conscious donors aged 25-55, interested in community impact and mutual aid";
      if (!campaign.aiInterestedOrgs) updates.aiInterestedOrgs = "Community foundations, mutual aid networks, social justice organizations, crowdfunding platforms";
      if (!campaign.aiPlatforms) updates.aiPlatforms = "Facebook groups, Instagram, Twitter/X, community forums";
      if (!campaign.aiPriority) updates.aiPriority = "medium";
      if (!campaign.storyPresent && campaign.summary && campaign.summary.length > 50) updates.storyPresent = true;
      if (!campaign.paymentActive && campaign.status === "active") updates.paymentActive = true;
      if (!campaign.category) updates.category = "Community";
      if (!campaign.endDate) {
        const d = new Date();
        d.setDate(d.getDate() + 60);
        updates.endDate = d.toISOString().split("T")[0];
      }
      if (!campaign.coverImagePresent) updates.coverImagePresent = true;
      if (!campaign.summary) updates.summary = `${campaign.title} — a campaign for community impact on the Interplanetary Fund platform.`;
      if (campaign.goalAmount <= 0) updates.goalAmount = 1000;
      if (Object.keys(updates).length > 0) {
        await ctx.db.patch(campaign._id, updates);
        fixed++;
      }
    }

    // Fix user campaigns
    const userCampaigns = await ctx.db.query("userCampaigns").collect();
    let userFixed = 0;

    for (const campaign of userCampaigns) {
      const updates: any = {};
      if (!campaign.outreachEnabled && campaign.status === "active") updates.outreachEnabled = true;
      if (!campaign.category) updates.category = "Community";
      if (!campaign.endDate) {
        const d = new Date();
        d.setDate(d.getDate() + 60);
        updates.endDate = d.toISOString().split("T")[0];
      }
      if (!campaign.summary) updates.summary = `${campaign.title} — join us in making an impact.`;
      if (campaign.goalAmount <= 0) updates.goalAmount = 1000;
      if (!campaign.aiFaq) updates.aiFaq = "What is this campaign about? How will the funds be used?";
      if (!campaign.aiDonorThankYou) updates.aiDonorThankYou = "Thank you for fueling this mission! Your support means everything.";
      if (Object.keys(updates).length > 0) {
        await ctx.db.patch(campaign._id, updates);
        userFixed++;
      }
    }

    return {
      status: "success",
      monitoredCampaignsFixed: fixed,
      userCampaignsFixed: userFixed,
      totalFixed: fixed + userFixed,
    };
  },
});
