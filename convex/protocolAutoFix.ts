// =====================================================
// HELPER: Normalize campaign from either table
// =====================================================
function normalizeMonitored(c: any) {
  return {
    _id: c._id,
    table: "monitoredCampaigns" as const,
    ifCampaignId: c.ifCampaignId,
    title: c.title,
    status: c.status,
    goalAmount: c.goalAmount || 0,
    raisedAmount: c.raisedAmount || 0,
    donorCount: c.donorCount || 0,
    category: c.category || "",
    summary: c.summary || "",
    story: c.summary || "",
    storyPresent: c.storyPresent ?? false,
    outreachEnabled: c.outreachEnabled ?? false,
    paymentActive: c.paymentActive ?? false,
    aiTone: c.aiTone || "",
    aiIdealDonors: c.aiIdealDonors || "",
    aiInterestedOrgs: c.aiInterestedOrgs || "",
    aiPlatforms: c.aiPlatforms || "",
    aiPriority: c.aiPriority || "",
    coverImagePresent: c.coverImagePresent ?? false,
    endDate: c.endDate || "",
    frozen: c.frozen ?? false,
    userId: null,
  };
}

function normalizeUser(c: any) {
  return {
    _id: c._id,
    table: "userCampaigns" as const,
    ifCampaignId: c._id, // user campaigns use _id as their campaign ID
    title: c.title,
    status: c.status,
    goalAmount: c.goalAmount || 0,
    raisedAmount: c.raisedAmount || 0,
    donorCount: c.donorCount || 0,
    category: c.category || "",
    summary: c.summary || "",
    story: c.story || "",
    storyPresent: (c.story && c.story.length > 50) || (c.summary && c.summary.length > 50) || false,
    outreachEnabled: c.outreachEnabled ?? false,
    paymentActive: c.status === "active", // user campaigns are active = payment active
    aiTone: c.aiFaq ? "AI-assisted" : "",
    aiIdealDonors: "",
    aiInterestedOrgs: "",
    aiPlatforms: c.aiSocialCaptions ? "AI-generated" : "",
    aiPriority: c.outreachEnabled ? "medium" : "",
    coverImagePresent: !!c.coverImageUrl,
    endDate: c.endDate || "",
    frozen: false,
    userId: c.userId,
  };
}

// Map of what fields to patch on each table
function getPatchFields(table: string, updates: Record<string, any>): Record<string, any> {
  if (table === "userCampaigns") {
    // Map monitored fields to user campaign fields
    const userUpdates: Record<string, any> = {};
    if (updates.outreachEnabled !== undefined) userUpdates.outreachEnabled = updates.outreachEnabled;
    if (updates.category !== undefined) userUpdates.category = updates.category;
    if (updates.endDate !== undefined) userUpdates.endDate = updates.endDate;
    if (updates.summary !== undefined) userUpdates.summary = updates.summary;
    if (updates.goalAmount !== undefined) userUpdates.goalAmount = updates.goalAmount;
    // userCampaigns doesn't have aiTone/aiIdealDonors/etc but has aiFaq, aiSocialCaptions
    // If AI fields are being filled, populate the AI wizard fields instead
    if (updates.aiTone !== undefined && !userUpdates.aiFaq) userUpdates.aiFaq = "Campaign FAQ generated by AI optimization";
    if (updates.aiIdealDonors !== undefined) userUpdates.aiDonorThankYou = userUpdates.aiDonorThankYou || "Thank you for supporting this campaign!";
    return userUpdates;
  }
  return updates;
}

